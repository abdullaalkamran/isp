// Bundles each Edge Function with its ../_shared imports into ONE file for the Supabase dashboard editor.
// `npm:` and `node:` imports stay external (Deno resolves them). Usage: npm run bundle:functions
import { build } from 'rolldown'
import { readdirSync, statSync } from 'node:fs'

const dir = 'supabase/functions'
const fns = readdirSync(dir).filter((n) => !n.startsWith('_') && statSync(`${dir}/${n}`).isDirectory())
for (const name of fns) {
  await build({
    input: `${dir}/${name}/index.ts`,
    platform: 'neutral',
    external: [/^npm:/, /^node:/],
    output: { file: `supabase/dashboard/${name}.ts`, format: 'esm', minify: false, banner: `// Single-file bundle of supabase/functions/${name} (generated by npm run bundle:functions). Paste into the dashboard editor.\n` },
    logLevel: 'warn',
  })
  console.log('bundled', name)
}
